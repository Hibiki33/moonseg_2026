"""Explicit sample admission. Discovery never grants permission to train."""
from __future__ import annotations

import csv
import json
import re
from pathlib import Path

TRAIN_SCENES = frozenset((1, 3, 5, 6, 7, 8))
TEST_SCENES = frozenset((2, 4, 9))


def scene_number(value):
    match = re.fullmatch(r"(?:Moon[_-]?)?(\d+)", str(value), flags=re.IGNORECASE)
    if not match or int(match[1]) not in range(1, 10):
        raise ValueError(f"Invalid scene: {value}")
    return int(match[1])


def read_allowlist(path):
    """JSON samples, CSV scene/sample_id, or one globally unique sample ID per text line.

    This must be the organizer's explicit sample list (or a faithful transcription),
    never a list generated by scanning the public archives.
    """
    path = Path(path)
    if not path.is_file():
        raise FileNotFoundError(f"Official sample allowlist missing: {path}")
    if path.suffix.lower() == ".json":
        value = json.loads(path.read_text(encoding="utf-8"))
        rows = value.get("samples") if isinstance(value, dict) else value
    elif path.suffix.lower() == ".jsonl":
        rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]
    elif path.suffix.lower() == ".csv":
        with path.open(encoding="utf-8", newline="") as stream:
            rows = list(csv.DictReader(stream))
    else:
        rows = [line.strip() for line in path.read_text(encoding="utf-8").splitlines()
                if line.strip() and not line.lstrip().startswith("#")]
    if not isinstance(rows, list) or not rows:
        raise ValueError("Official allowlist must contain a nonempty list of samples")
    keys = set()
    for row in rows:
        if isinstance(row, str):
            key = (None, row)
        elif isinstance(row, dict) and "sample_id" in row:
            scene = row.get("scene")
            key = (scene_number(scene) if scene is not None and scene != "" else None, str(row["sample_id"]))
        else:
            raise ValueError("Allowlist entries need sample_id and optionally scene")
        if key in keys:
            raise ValueError(f"Duplicate allowlist sample: {key}")
        keys.add(key)
    return keys


def is_allowed(record, allowlist):
    return (int(record["scene"]), str(record["sample_id"])) in allowlist or (None, str(record["sample_id"])) in allowlist


def require_complete_allowlist(records, allowlist):
    keys = {(int(record["scene"]), str(record["sample_id"])) for record in records}
    ids = {key[1] for key in keys}
    missing = [(scene, sample_id) for scene, sample_id in allowlist
               if (sample_id not in ids if scene is None else (scene, sample_id) not in keys)]
    if missing:
        raise ValueError(f"Manifest omits {len(missing)} official samples; first entries: {missing[:8]}")


def validate_sample(record, root, need_label, allowed_scenes):
    scene = scene_number(record["scene"])
    if scene not in allowed_scenes:
        raise ValueError(f"Scene {scene} is not admitted in this split")
    sample_id = str(record["sample_id"])
    if not sample_id or sample_id in (".", "..") or "/" in sample_id or "\\" in sample_id:
        raise ValueError(f"Unsafe sample ID: {sample_id!r}")
    for field in (("image", "label") if need_label else ("image",)):
        relative = Path(record[field])
        if relative.suffix.lower() != ".png" or relative.stem != sample_id:
            raise ValueError(f"{field} filename must match sample_id as a PNG: {record}")
        path = (root / relative).resolve()
        if relative.is_absolute() or not path.is_relative_to(root.resolve()):
            raise ValueError(f"{field} must be a relative path inside data.root")
        for component in relative.parts:
            match = re.fullmatch(r"Moon[_-]?(\d+)", component, flags=re.IGNORECASE)
            if match and int(match[1]) != scene:
                raise ValueError(f"Sample scene/path mismatch: {record}")
        if not path.is_file():
            raise FileNotFoundError(path)


def load_manifest(path, root, allowed_scenes, official_allowlist=None, need_label=True):
    value = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(value, dict) or "samples" not in value:
        raise ValueError("Manifest must be a JSON object with a samples list")
    if need_label and value.get("kind") != "official_train_manifest":
        raise ValueError("Training/evaluation requires an official_train_manifest; public discovery is not an official sample list")
    if need_label and official_allowlist is None:
        raise ValueError("Set data.official_allowlist to the explicit organizer training sample list")
    allowlist = read_allowlist(official_allowlist) if official_allowlist else None
    root = Path(root)
    records = value["samples"]
    if not records:
        raise ValueError(f"Empty manifest: {path}")
    seen = set()
    for record in records:
        validate_sample(record, root, need_label, allowed_scenes)
        key = str(record["sample_id"])
        if key in seen:
            raise ValueError(f"Duplicate globally unique sample_id: {key}")
        seen.add(key)
        if allowlist is not None and not is_allowed(record, allowlist):
            raise ValueError(f"Sample is absent from official allowlist: {record['scene']}/{key}")
    return records
